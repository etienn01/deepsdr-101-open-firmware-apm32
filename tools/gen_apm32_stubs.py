#!/usr/bin/env python3
"""Generates User/apm32_stubs.c: no-op entry points for the modes left out of the APM32 build (APM32_EXCLUDE in
reglas.mk). Function names come from the symbols the linker reports as undefined, plus those already in the file;
prototypes are read from User/*.h.

Usage: make apm32 2>&1 | python3 tools/gen_apm32_stubs.py
"""
import glob
import re
import sys

OUT = 'User/apm32_stubs.c'

names = set(re.findall(r"undefined reference to `([^']+)'", sys.stdin.read()))
try:
    names |= set(re.findall(r'^[\w\s\*]*?\b(\w+)\([^;{]*\)\n\{', open(OUT).read(), re.M))
except FileNotFoundError:
    pass

hdrs = {}
for h in sorted(glob.glob('User/*.h')):
    t = open(h, encoding='utf-8', errors='replace').read()
    t = re.sub(r'/\*.*?\*/', ' ', t, flags=re.S)
    hdrs[h] = re.sub(r'//[^\n]*', ' ', t)

protos = []
for n in sorted(names):
    for h, t in hdrs.items():
        m = re.search(r'(^|[;}\n])\s*((?:extern\s+)?(?:const\s+)?[A-Za-z_][\w\s\*]*?[\s\*])' + re.escape(n)
                      + r'\s*\(([^;{]*?)\)\s*;', t, re.S)
        if m:
            protos.append((h, ' '.join(m.group(2).replace('extern', '').split()), n, ' '.join(m.group(3).split())))
            break
    else:
        sys.exit('no prototype found for ' + n)

SPECIAL = {
    'ft8_decoder_get_own_grid': '    return s_own_grid;',
    'ft8_decoder_set_own_grid': ('    int i;\n'
                                 "    for (i = 0; i < len && i < (int)sizeof s_own_grid - 1 && grid[i] != '\\0'; i++)\n"
                                 '        s_own_grid[i] = grid[i];\n'
                                 "    s_own_grid[i] = '\\0';"),
    'mapa_bin_abre_flash': '    (void)lee; (void)base; (void)n;\n    return MAPA_BIN_NADA;',
    'mapa_bin_estado': '    return MAPA_BIN_NADA;',
}


def body(ret, name, args):
    if name in SPECIAL:
        return SPECIAL[name]
    unused = []
    if args and args != 'void':
        for a in re.split(r',(?![^()]*\))', args):
            m = re.search(r'\(\s*\*\s*(\w+)\s*\)|(\w+)\s*(\[[^\]]*\])?\s*$', a.strip())
            unused.append('(void)%s;' % (m.group(1) or m.group(2)))
    pre = ('    ' + ' '.join(unused) + '\n') if unused else ''
    r = ret.replace(' ', '')
    if r == 'void':
        return pre.rstrip('\n') if pre else '    /* left out of the APM32 build */'
    if r.endswith('*') and 'char' in r:
        return pre + '    return "";'
    if r.endswith('*'):
        return pre + '    return 0;'
    if r == 'bool':
        return pre + '    return false;'
    if r == 'float':
        return pre + '    return 0.0f;'
    if r == 'mapa_bin_r_t':
        return pre + '    return MAPA_BIN_NADA;'
    return pre + '    return 0;'


out = ['/*',
       ' * APM32F407 build only: no-op entry points for the modes left out of it (see APM32_EXCLUDE in reglas.mk),',
       " * because the APM32F407 has 128 KB of main RAM instead of the GD32F450's 192 KB. Every query answers",
       ' * "nothing there / not running", so the rest of the firmware behaves as if the mode had produced nothing.',
       ' * Generated by tools/gen_apm32_stubs.py - do not edit by hand.',
       ' */',
       '#ifdef CHIP_APM32F407',
       '#include <stdbool.h>', '#include <stddef.h>', '#include <stdint.h>']
out += ['#include "%s"' % h[5:] for h in sorted({p[0] for p in protos})]
out += ['', '/* The own Maidenhead locator is kept by the FT8 decoder; hold it here so the QTH setting still works. */',
        'static char s_own_grid[7] = "";', '']
cur = None
for h, ret, n, args in sorted(protos, key=lambda p: (p[0], p[2])):
    if h != cur:
        out.append('/* --- %s --- */' % h[5:])
        cur = h
    out += ['%s%s%s(%s)' % (ret, '' if ret.endswith('*') else ' ', n, args), '{', body(ret, n, args), '}', '']
out.append('#endif /* CHIP_APM32F407 */')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('%d stubs written to %s' % (len(protos), OUT))
