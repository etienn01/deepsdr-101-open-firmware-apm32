#!/usr/bin/env python3
"""Generates User/fft_tables.h: the FFT twiddle, Hann window and bit-reversal tables of User/fft.c as constants in
flash, so the APM32 build does not spend 5 KB of CCM computing them at boot (see fft_init()).

The values are computed exactly like fft_init() does: same Bhaskara sine approximation, same float32 operation
order, so the spectrum is unchanged. Usage: python3 tools/gen_fft_tables.py 512 > User/fft_tables.h
"""
import struct
import sys

import numpy as np

f32 = np.float32
PI = f32(3.14159265358979)


def sinf_approx_local(x):
    x = f32(x)
    negate = False
    while x > PI:
        x = f32(x - f32(f32(2.0) * PI))
    while x < -PI:
        x = f32(x + f32(f32(2.0) * PI))
    if x < f32(0.0):
        x = f32(-x)
        negate = True
    pmx = f32(PI - x)
    num = f32(f32(f32(f32(16.0) * x) * pmx))
    den = f32(f32(f32(f32(5.0) * PI) * PI) - f32(f32(f32(4.0) * x) * pmx))
    r = f32(num / den)
    return f32(-r) if negate else r


def cosf_approx_local(x):
    return sinf_approx_local(f32(f32(x) + f32(PI / f32(2.0))))


def hexf(v):
    """Exact float literal: the IEEE bits, as a hexadecimal float that C reads back bit for bit."""
    return float(v).hex() + 'f'


def main():
    n = int(sys.argv[1])
    bits = n.bit_length() - 1
    assert 1 << bits == n, 'FFT size must be a power of two'
    cos_t, sin_t, hann, bitrev = [], [], [], []
    for k in range(n // 2):
        angle = f32(f32(f32(f32(-2.0) * PI) * f32(k)) / f32(n))
        cos_t.append(cosf_approx_local(angle))
        sin_t.append(sinf_approx_local(angle))
    for k in range(n):
        arg = f32(f32(f32(f32(2.0) * PI) * f32(k)) / f32(n - 1))
        hann.append(f32(f32(0.5) - f32(f32(0.5) * cosf_approx_local(arg))))
    for k in range(n):
        v, r = k, 0
        for _ in range(bits):
            r = (r << 1) | (v & 1)
            v >>= 1
        bitrev.append(r)

    def rows(vals, per_line, fmt):
        return '\n'.join('    ' + ', '.join(fmt(v) for v in vals[i:i + per_line]) + ','
                         for i in range(0, len(vals), per_line))

    print('/* Generated by tools/gen_fft_tables.py %d - do not edit. See fft_init() in fft.c. */' % n)
    print('#ifndef FFT_TABLES_H')
    print('#define FFT_TABLES_H')
    print('#include <stdint.h>')
    print('#define FFT_TABLES_SIZE %dU' % n)
    print('static const float k_fft_twiddle_cos[%d] = {\n%s\n};' % (n // 2, rows(cos_t, 4, hexf)))
    print('static const float k_fft_twiddle_sin[%d] = {\n%s\n};' % (n // 2, rows(sin_t, 4, hexf)))
    print('static const float k_fft_hann[%d] = {\n%s\n};' % (n, rows(hann, 4, hexf)))
    print('static const uint16_t k_fft_bitrev[%d] = {\n%s\n};' % (n, rows(bitrev, 16, str)))
    print('#endif /* FFT_TABLES_H */')


if __name__ == '__main__':
    main()
